-- ACT02 preparation template. The definer is a separately created LOCKED SQL
-- account with TRIGGER on the exact target schema only, no global privileges.
-- Runtime receives EXECUTE on this fixed no-argument reader, never TRIGGER/DDL.
DELIMITER $$
CREATE DEFINER={{METADATA_DEFINER}} PROCEDURE act02_trigger_metadata()
READS SQL DATA SQL SECURITY DEFINER
BEGIN
 SELECT TRIGGER_NAME,EVENT_MANIPULATION,EVENT_OBJECT_TABLE,ACTION_TIMING,ACTION_STATEMENT,DEFINER,ACTION_ORDER,SQL_MODE,CHARACTER_SET_CLIENT,COLLATION_CONNECTION,DATABASE_COLLATION
 FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='{{TARGET_SCHEMA_NAME}}' ORDER BY TRIGGER_NAME;
 SELECT ROUTINE_DEFINITION,DEFINER,SECURITY_TYPE,SQL_DATA_ACCESS
 FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA='{{TARGET_SCHEMA_NAME}}' AND ROUTINE_NAME='act02_trigger_metadata';
END$$
DELIMITER ;
GRANT EXECUTE ON PROCEDURE `{{TARGET_SCHEMA_NAME}}`.act02_trigger_metadata TO {{METADATA_DEFINER}};
