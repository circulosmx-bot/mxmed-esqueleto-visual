-- GOV-SIM02: PREPARED ONLY. NOT AUTHORIZED FOR mxmed. No seed or legacy backfill.
-- One C4/ADM02 admission decision authority, referenced by the Identity binding.
-- No mandatory twelve-month review: deadlines come from approved source evidence.
CREATE TABLE profiles_physician_admissions (
 admission_id CHAR(36) NOT NULL PRIMARY KEY,
 doctor_id VARCHAR(64) NOT NULL,
 verified_identity_id BIGINT UNSIGNED NOT NULL,
 professional_credential_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 authority_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 reviewed_by_account_id VARCHAR(64) NOT NULL,
 case_reference VARCHAR(128) NOT NULL,
 decision_reference VARCHAR(128) NOT NULL,
 audit_reference VARCHAR(128) NOT NULL,
 evidence_reference VARCHAR(190) NOT NULL,
 approved_at DATETIME(6) NULL,
 valid_from DATETIME(6) NOT NULL,
 valid_until DATETIME(6) NULL,
 reverify_at DATETIME(6) NULL,
 UNIQUE KEY uq_physician_admission_profile (doctor_id),
 FOREIGN KEY (doctor_id) REFERENCES profiles_doctors(doctor_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY (verified_identity_id) REFERENCES profiles_verified_identities(verified_identity_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY (doctor_id,professional_credential_id) REFERENCES profiles_doctor_credentials(doctor_id,credential_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY (reviewed_by_account_id) REFERENCES internal_staff(account_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CHECK (status IN ('PENDING','APPROVED','REJECTED','SUSPENDED','REVOKED','EXPIRED')),
 CHECK (authority_version>0),
 CHECK (status<>'APPROVED' OR approved_at IS NOT NULL),
 CHECK (valid_until IS NULL OR valid_until>valid_from),
 CHECK (reverify_at IS NULL OR reverify_at>valid_from),
 CHECK (CHAR_LENGTH(TRIM(case_reference))>0 AND CHAR_LENGTH(TRIM(decision_reference))>0
   AND CHAR_LENGTH(TRIM(audit_reference))>0 AND CHAR_LENGTH(TRIM(evidence_reference))>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE auth_account_professional_bindings (
 binding_id CHAR(36) NOT NULL PRIMARY KEY,
 account_id VARCHAR(64) NOT NULL,
 profile_doctor_id VARCHAR(64) NOT NULL,
 admission_id CHAR(36) NOT NULL,
 admission_version BIGINT UNSIGNED NOT NULL,
 verified_identity_id BIGINT UNSIGNED NOT NULL,
 identity_revision_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 credential_revision_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 authority_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 relationship_evidence_reference VARCHAR(190) NOT NULL,
 acceptance_reference VARCHAR(128) NOT NULL,
 audit_reference VARCHAR(128) NOT NULL,
 valid_from DATETIME(6) NOT NULL,
 valid_until DATETIME(6) NULL,
 reverify_at DATETIME(6) NULL,
 active_account VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN status IN ('PENDING','ACTIVE','SUSPENDED') THEN account_id ELSE NULL END) STORED,
 active_profile VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN status IN ('PENDING','ACTIVE','SUSPENDED') THEN profile_doctor_id ELSE NULL END) STORED,
 active_identity BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status IN ('PENDING','ACTIVE','SUSPENDED') THEN verified_identity_id ELSE NULL END) STORED,
 UNIQUE KEY uq_professional_binding_account_profile (active_account,active_profile),
 UNIQUE KEY uq_professional_binding_identity (active_identity),
 FOREIGN KEY (account_id) REFERENCES auth_accounts(account_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY (profile_doctor_id) REFERENCES profiles_doctors(doctor_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY (verified_identity_id) REFERENCES profiles_verified_identities(verified_identity_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY (admission_id) REFERENCES profiles_physician_admissions(admission_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CHECK (status IN ('PENDING','ACTIVE','SUSPENDED','REVOKED','REJECTED','EXPIRED')),
 CHECK (authority_version>0 AND admission_version>0),
 CHECK (identity_revision_hash REGEXP '^[a-f0-9]{64}$' AND credential_revision_hash REGEXP '^[a-f0-9]{64}$'),
 CHECK (valid_until IS NULL OR valid_until>valid_from),
 CHECK (reverify_at IS NULL OR reverify_at>valid_from),
 CHECK (CHAR_LENGTH(TRIM(relationship_evidence_reference))>0 AND CHAR_LENGTH(TRIM(acceptance_reference))>0 AND CHAR_LENGTH(TRIM(audit_reference))>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
